


    .section .data 

# 3×3 matrix A (row-major)
A:

    .word 0x3f800000   # 1.0
    .word 0x00000000   # 0.0
    .word 0x00000000   # 0.0

    .word 0x00000000   # 0.0
    .word 0x40000000   # 2.0
    .word 0x00000000   # 0.0

    .word 0x00000000   # 0.0
    .word 0x00000000   # 0.0
    .word 0x40400000   # 3.0


lambda_out:
    .word 0x00000000   # (unused now)



    .section .text

############################################################
# Initial x = [1,1,1]
############################################################

    li t0, 1
    fcvt.s.w  f0, t0     # x0
    fcvt.s.w  f1, t0     # x1
    fcvt.s.w  f2, t0     # x2

############################################################
# Loop counter = 20 power iterations
############################################################
addi t3, x0, 20

power_loop:

############################################################
# y = A * x
############################################################
    la t1, A

    # ---- row 0 ----
    flw     f10, 0(t1)
    fmul.s  f20, f10, f0
    flw     f11, 4(t1)
    fmul.s  f21, f11, f1
    fadd.s  f20, f20, f21
    flw     f12, 8(t1)
    fmul.s  f21, f12, f2
    fadd.s  f20, f20, f21      # y0

    # ---- row 1 ----
    flw     f13, 12(t1)
    fmul.s  f22, f13, f0
    flw     f14, 16(t1)
    fmul.s  f23, f14, f1
    fadd.s  f22, f22, f23
    flw     f15, 20(t1)
    fmul.s  f23, f15, f2
    fadd.s  f22, f22, f23      # y1

    # ---- row 2 ----
    flw     f16, 24(t1)
    fmul.s  f24, f16, f0
    flw     f17, 28(t1)
    fmul.s  f25, f17, f1
    fadd.s  f24, f24, f25
    flw     f18, 32(t1)
    fmul.s  f25, f18, f2
    fadd.s  f24, f24, f25      # y2

############################################################
# Normalize y → x
############################################################

    fmul.s  f26, f20, f20
    fmul.s  f27, f22, f22
    fadd.s  f26, f26, f27
    fmul.s  f27, f24, f24
    fadd.s  f26, f26, f27
    fsqrt.s f26, f26            # norm

    fdiv.s  f0, f20, f26        # x0'
    fdiv.s  f1, f22, f26        # x1'
    fdiv.s  f2, f24, f26        # x2'

############################################################
# Loop iteration
############################################################
    addi t3, t3, -1
    bne t3, x0, power_loop


############################################################
# Compute Rayleigh quotient λ = xᵀ (A x)
############################################################

    la t1, A

    # ---- row 0 ----
    flw     f10, 0(t1)
    fmul.s  f20, f10, f0
    flw     f11, 4(t1)
    fmul.s  f21, f11, f1
    fadd.s  f20, f20, f21
    flw     f12, 8(t1)
    fmul.s  f21, f12, f2
    fadd.s  f20, f20, f21      # Ax0

    # ---- row 1 ----
    flw     f13, 12(t1)
    fmul.s  f22, f13, f0
    flw     f14, 16(t1)
    fmul.s  f23, f14, f1
    fadd.s  f22, f22, f23
    flw     f15, 20(t1)
    fmul.s  f23, f15, f2
    fadd.s  f22, f22, f23      # Ax1


    # ---- row 2 ----
    flw     f16, 24(t1)
    fmul.s  f24, f16, f0
    flw     f17, 28(t1)
    fmul.s  f25, f17, f1
    fadd.s  f24, f24, f25
    flw     f18, 32(t1)
    fmul.s  f25, f18, f2
    fadd.s  f24, f24, f25      # Ax2

############################################################
# λ = x0*Ax0 + x1*Ax1 + x2*Ax2
############################################################
    fmul.s  f28, f0, f20
    fmul.s  f29, f1, f22
    fadd.s  f28, f28, f29
    fmul.s  f30, f2, f24
    fadd.s  f28, f28, f30      # f28 = eigenvalue

############################################################
# Store λ at ABSOLUTE ADDRESS 0x00000000
############################################################
    li   t2, 0x000
    fsw  f28, 0(t2)

############################################################
# Halt (infinite loop)
############################################################
halt:
    jal x0, halt

